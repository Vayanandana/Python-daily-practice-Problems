'''
Docstring for Day-35.Calculate-the-Perimeter-of-a-Rectangle
Let's learn how to calculate the perimeter of a rectangle using Python step by step.

Step 1: Understand the problem
We need to write a program that calculates the perimeter of a rectangle. The formula to calculate the perimeter of a rectangle is:

Perimeter = 2 × (Length + Breadth)

We'll get the length and breadth from the user as input, and then calculate the perimeter.

Step 2: Get the length and breadth from the user
First, let's ask the user to enter the length and breadth of the rectangle. We'll use the input() function to get the values.
'''
length_rectangle =input()
breadth_rectangle =input()

length_rectangle = int(length_rectangle )
breadth_rectangle = int(breadth_rectangle)
area = 2 *  (length_rectangle + breadth_rectangle)
result = area 
print(result)